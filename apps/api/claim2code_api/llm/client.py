def _build_user_payload(paper: Paper) -> str:
    """Serialize the parsed paper into the user-message text.

    Phase 2 v1 includes only sections + text — equations and tables
    are part of the parsed ``Paper`` but are not surfaced in the v1
    claim-extraction prompt (see ``docs/architecture/phase-2-design.md``
    §3 "what we explicitly do NOT do").
    """
    sections_md = []
    for section in paper.sections:
        heading = section.title or "(preamble)"
        sections_md.append(f"## {heading}\n\n{section.text}\n")
    return (
        f"# Paper: {paper.filename}\n"
        f"Pages: {paper.n_pages}  Chars: {paper.n_chars}\n\n"
        + "\n".join(sections_md)
    )


def _build_verify_payload(
    *,
    claim: Claim,
    paper_evidence: PaperEvidence,
    candidates: list[RetrieveMatch],
    deterministic_discrepancies: list[Discrepancy],
) -> str:
    """Build the verifier's user-message text.

    Sections:

      - **# Claim** — the claim's text + type + the paper
        evidence (section + page + verbatim quote).
      - **# Deterministic discrepancies** — what the regex-based
        checkers already found. The LLM is told not to re-emit
        these (per the system prompt rule 5).
      - **# Candidates** — up to 5 RetrieveMatch entries,
        rendered with symbol_id, file_path, line range, name,
        signature, and docstring. The LLM must cite from this
        list when emitting code_evidence (per the system prompt
        rule 1).

    The payload stays human-readable: the LLM does NOT need to
    parse a JSON structure to find the inputs.
    """
    parts: list[str] = []

    parts.append(
        f"# Claim\n\n"
        f"claim_id: {claim.claim_id}\n"
        f"type: {claim.claim_type}\n"
        f"text: {claim.text}\n\n"
        f"# Paper evidence\n\n"
        f"section: {paper_evidence.section_title}\n"
        f"page: {paper_evidence.page}\n"
        f"quote (verbatim):\n\n"
        f">>> {paper_evidence.quote} <<<\n"
    )

    if deterministic_discrepancies:
        parts.append("# Deterministic discrepancies (already found)\n")
        for d in deterministic_discrepancies:
            parts.append(f"- {d.type.value} [{d.severity.value}]: {d.detail}")
        parts.append("")

    if candidates:
        parts.append(f"# Candidates ({len(candidates)})\n")
        for i, c in enumerate(candidates, start=1):
            parts.append(
                f"## Candidate {i}\n"
                f"symbol_id: {c.symbol_id}\n"
                f"file: {c.file_path}:{c.start_line}-{c.end_line}\n"
                f"name: {c.name}\n"
                f"signature: {c.signature}\n"
            )
            if c.docstring:
                parts.append(f"docstring: {c.docstring}\n")
            parts.append("")
    else:
        parts.append("# Candidates\n\n(none — top-K retrieval returned empty)\n")

    return "\n".join(parts)


def _build_compare_payload(*, claim: Claim, paper: ScholarPaper) -> str:
    """Build the comparator's user-message text.

    Sections:

      - **# Claim** — the claim's text + type. We deliberately do
        NOT include the paper evidence here — the comparator is
        cross-paper, so the claim + the candidate paper's
        abstract are sufficient.
      - **# Related paper** — title, authors, year, venue, optional
        TLDR (S2's pre-trained model summary), and abstract. The
        LLM must cite from these fields per the system-prompt rule
        (no model knowledge).

    Mirrors the verbosity of :func:`_build_verify_payload` so the
    LLM gets consistent inputs (no JSON-wrapped payloads).
    """
    authors_str = ", ".join(paper.authors) if paper.authors else "(unknown)"
    venue_str = paper.venue if paper.venue else "(unknown)"
    tldr_block = f"\ntldr: {paper.tldr}\n" if paper.tldr else "\ntldr: (not provided)\n"

    return (
        f"# Claim\n\n"
        f"claim_id: {claim.claim_id}\n"
        f"type: {claim.claim_type}\n"
        f"text: {claim.text}\n\n"
        f"# Related paper\n\n"
        f"paper_id: {paper.paper_id}\n"
        f"title: {paper.title}\n"
        f"authors: {authors_str}\n"
        f"year: {paper.year}\n"
        f"venue: {venue_str}\n"
        f"citation_count: {paper.citation_count}\n"
        f"{tldr_block}\n"
        f"abstract (verbatim):\n\n"
        f">>> {paper.abstract} <<<\n"
    )