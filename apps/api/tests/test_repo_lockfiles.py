def test_yarn_lock(tmp_path: Path) -> None:
    p = tmp_path / "yarn.lock"
    p.write_text(
        "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT.\n"
        'react@^18.0.0:\n  version "18.2.0"\n'
        'lodash@^4.17.0:\n  version "4.17.21"\n'
    )
    rows = parse_lockfile(p, "yarn.lock")
    names = {r.name for r in rows}
    assert names == {"react", "lodash"}


