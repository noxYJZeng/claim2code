"""Unit tests for :mod:`claim2code_api.repos.lockfiles`."""

from __future__ import annotations

from pathlib import Path

from claim2code_api.repos.lockfiles import parse_lockfile
from claim2code_api.repos.schemas import DependencyEcosystem

# ============================================================
# requirements.txt
# ============================================================


def test_requirements_txt_basic(tmp_path: Path) -> None:
    p = tmp_path / "requirements.txt"
    p.write_text(
        "# comment line\n"
        "\n"
        "requests==2.31.0\n"
        "numpy>=1.24\n"
        "scipy~=1.11\n"
        "-e git+https://example.com/foo.git#egg=foo\n"  # editable line skipped
    )
    rows = parse_lockfile(p, "requirements.txt")
    assert len(rows) == 3
    by_name = {r.name: r for r in rows}
    assert by_name["requests"].version_spec == "==2.31.0"
    assert by_name["numpy"].version_spec == ">=1.24"
    assert by_name["scipy"].version_spec == "~=1.11"
    assert all(r.ecosystem is DependencyEcosystem.PYPI for r in rows)
    assert all(r.source_file == "requirements.txt" for r in rows)


def test_requirements_txt_with_extras(tmp_path: Path) -> None:
    p = tmp_path / "requirements-dev.txt"
    p.write_text("uvicorn[standard]>=0.30\nfastapi>=0.115\n")
    rows = parse_lockfile(p, "requirements-dev.txt")
    assert any(r.name.startswith("uvicorn[") for r in rows)


def test_requirements_txt_env_marker(tmp_path: Path) -> None:
    p = tmp_path / "requirements.txt"
    p.write_text('requests==2.31.0 ; python_version >= "3.10"\n')
    rows = parse_lockfile(p, "requirements.txt")
    assert rows[0].name == "requests"
    assert "==2.31.0" in rows[0].version_spec


def test_requirements_txt_empty(tmp_path: Path) -> None:
    p = tmp_path / "requirements.txt"
    p.write_text("")
    assert parse_lockfile(p, "requirements.txt") == []


# ============================================================
# poetry.lock
# ============================================================


def test_poetry_lock(tmp_path: Path) -> None:
    p = tmp_path / "poetry.lock"
    p.write_text(
        '{"package": ['
        '{"name": "torch", "version": "2.1.0"},'
        '{"name": "numpy", "version": "1.24.0"}'
        "]}"
    )
    rows = parse_lockfile(p, "poetry.lock")
    assert len(rows) == 2
    by_name = {r.name: r for r in rows}
    assert by_name["torch"].version_spec == "==2.1.0"
    assert all(r.ecosystem is DependencyEcosystem.PYPI for r in rows)


def test_poetry_lock_malformed(tmp_path: Path) -> None:
    p = tmp_path / "poetry.lock"
    p.write_text("{not valid json")
    assert parse_lockfile(p, "poetry.lock") == []


# ============================================================
# Pipfile.lock
# ============================================================


def test_pipfile_lock(tmp_path: Path) -> None:
    p = tmp_path / "Pipfile.lock"
    p.write_text(
        '{"_meta": {},'
        '"default": {"requests": {"version": "==2.31.0"}, "fastapi": {"version": "==0.115.0"}},'
        '"develop": {"pytest": {"version": "==8.2.0"}}}'
    )
    rows = parse_lockfile(p, "Pipfile.lock")
    assert len(rows) == 3
    names = {r.name for r in rows}
    assert names == {"requests", "fastapi", "pytest"}


# ============================================================
# package-lock.json (lockfileVersion 2/3)
# ============================================================


def test_package_lock_json_v2(tmp_path: Path) -> None:
    p = tmp_path / "package-lock.json"
    p.write_text(
        '{"packages": {'
        '"node_modules/react": {"version": "18.2.0"},'
        '"node_modules/lodash": {"version": "4.17.21"},'
        '"": {"name": "root", "version": "1.0.0"}'
        "}}"
    )
    rows = parse_lockfile(p, "package-lock.json")
    names = {r.name for r in rows}
    assert names == {"react", "lodash"}
    assert all(r.ecosystem is DependencyEcosystem.NPM for r in rows)


def test_package_lock_json_v1(tmp_path: Path) -> None:
    p = tmp_path / "package-lock.json"
    p.write_text(
        '{"dependencies": {"react": {"version": "18.2.0"},"lodash": {"version": "4.17.21"}}}'
    )
    rows = parse_lockfile(p, "package-lock.json")
    assert {r.name for r in rows} == {"react", "lodash"}


