"""OpenAI client wrapper with Structured Outputs + readiness probe.

Why a wrapper
-------------
We isolate the OpenAI SDK behind a thin class for two reasons:

  1. **Mockability.** Tests patch :func:`get_llm_client` (the same
     pattern ``get_engine`` uses), or inject a fake ``LLMClient``
     subclass, so unit tests never hit the network.
  2. **httpx proxy workaround.** The ``openai`` SDK accepts an
     ``http_client=`` kwarg. Behind certain corporate proxies the
     environment publishes ``all_proxy=socks://...``, which
     ``httpx>=0.28`` rejects. Passing our own
     ``httpx.Client(proxy=None)`` bypasses the env-var-derived proxy
     entirely — see ``memory/claim2code-local-env.md`` gotcha (4).

Structured Outputs
------------------
OpenAI's Structured Outputs (``response_format={"type": "json_schema",
"json_schema": {...}}`` with ``strict: true``) guarantees the model
response matches the schema or the call fails. We send the schema
generated by :meth:`claim2code_api.papers.schemas.ClaimList.model_json_schema`,
which encodes the ``min_items`` / ``max_items`` array constraints
(1-20 claims) that OpenAI enforces server-side.

Phase 6 will add a second method (``verdict_for_claim``) reusing the
same SDK client.
"""
from __future__ import annotations

import json
import logging
from threading import Lock

import httpx
from openai import (
    APIConnectionError,
    APIStatusError,
    APITimeoutError,
    AuthenticationError,
    OpenAI,
)
from pydantic import ValidationError

from claim2code_api.app.config import Settings, get_settings
from claim2code_api.literature.exceptions import LiteratureComparisonError
from claim2code_api.literature.schemas import Comparison, ScholarPaper
from claim2code_api.papers.exceptions import ClaimExtractionError
from claim2code_api.papers.schemas import Claim, ClaimList, Paper, PaperEvidence
from claim2code_api.repos.schemas import RetrieveMatch
from claim2code_api.safety import SafetyGate, SafetyViolation
from claim2code_api.verification.exceptions import VerificationLLMError
from claim2code_api.verification.schemas import (
    Discrepancy,
    Verification,
    VerificationStatus,
)

logger = logging.getLogger(__name__)

# Default timeout for one LLM call. Keep tight so a hung call doesn't
# burn the entire ``workflow_timeout_paper`` budget on a single attempt.
_DEFAULT_REQUEST_TIMEOUT_SECONDS = 60.0

# System prompt for claim extraction. Phrased as a rubric so the model
# knows the granularity boundary between METHOD vs IMPLEMENTATION, and
# that HYPERPARAMETER cites a verbatim value (not "we use a small
# learning rate").
_EXTRACT_SYSTEM_PROMPT = """\
You are a meticulous scientific-paper claim extractor. Given a paper's
sections and body text, you return a structured JSON list of 1-20
testable technical claims. Each claim must be:

  - **Specific**: cite a concrete hyperparameter / equation / dataset /
    method component, never a vague "we do well".
  - **Grounded**: include a verbatim ``quote`` from the section body
    (NOT the heading) and the section title + page number.
  - **Typed** with one of: METHOD, IMPLEMENTATION, PERFORMANCE,
    ABLATION, HYPERPARAMETER, DATASET, COMPLEXITY, TRAINING,
    EVALUATION (see the taxonomy in the schema).
  - **Confidence** between 0 and 1 (your certainty the claim is
    material to the paper's contribution, not its literal truth).

Reject boilerplate. Reject "we propose a novel approach" with no
specifics. If a section contains no testable claim, omit it.
"""

# System prompt for the verifier (Phase 6). The "no model knowledge"
# rule from docs/specs/spec-summary.md §10 is the most important
# single constraint — every piece of evidence must be a verbatim
# quote from the inputs we provide. The model must NOT bring in
# external knowledge of the paper, the library, or the algorithm.
_VERIFY_SYSTEM_PROMPT = """\
You are a meticulous paper-to-code verifier. Given (1) a technical
claim extracted from a paper, (2) a verbatim snippet of the paper
that grounds it, and (3) up to 5 candidate code symbols retrieved
from the reference implementation, judge whether the code actually
implements the claim.

RULES (non-negotiable):

  1. **No model knowledge.** Every piece of paper evidence you cite
     must be a verbatim substring of the paper_evidence.quote
     provided. Every piece of code evidence you cite must reference
     a specific candidate from the list provided (its symbol_id,
     file_path, line numbers, signature, or docstring). You MAY NOT
     use knowledge of the paper, the library, or the algorithm
     beyond what is explicitly given in the inputs.

  2. **One of four verdicts:**
       VERIFIED, PARTIALLY_VERIFIED, CONTRADICTED, UNVERIFIED.

       - VERIFIED only when >=1 candidate's signature/docstring
         directly implements the claim and no HIGH-severity
         discrepancies exist.
       - PARTIALLY_VERIFIED when >=1 candidate is relevant but
         discrepancies (LOW or MEDIUM severity) exist.
       - CONTRADICTED when a candidate clearly contradicts the
         claim or a HIGH-severity discrepancy exists.
       - UNVERIFIED when no candidate is relevant.

  3. **Extract structured hyperparameters** as part of your
     response: for any hyperparameter mentioned in the claim or
     quote (learning_rate, batch_size, temperature, beta, gamma,
     num_epochs, hidden_size), include {name, value, source} in
     your output. The deterministic checker cross-validates these
     against its own regex extraction.

  4. **Cite deterministically.** Each ``code_evidence`` entry must
     include ``symbol_id`` (UUID string), ``quote`` (verbatim from
     candidate.signature or candidate.docstring), and
     ``file_path`` + line numbers that match the candidate.

  5. The deterministic checker has already produced the following
     discrepancies (if any). You MAY add more of any severity, but
     do not re-emit the same type twice — focus on residual
     judgement, novel discrepancies, or AMBIGUOUS cases where the
     deterministic check is uncertain.

Output schema is enforced via Structured Outputs
(\`response_format\`.json_schema with strict=True). Any deviation
fails the call. If insufficient evidence is available, return
UNVERIFIED with an empty code_evidence list — do NOT guess.
"""

# System prompt for the comparator (Phase 7). Same no-model-knowledge
# rule as the verifier: every comparison field must cite the verbatim
# abstract or TLDR from the inputs. The 6-field output schema is
# enforced via Structured Outputs (response_format strict=True).
_COMPARE_SYSTEM_PROMPT = """\
You are a meticulous research-paper comparison analyst. Given
(1) a technical claim extracted from one paper, and (2) a related
paper's metadata (title, authors, year, venue, abstract, optional
TLDR), produce a structured 6-field comparison.

RULES (non-negotiable):

  1. **No model knowledge.** Every comparison field must cite the
     verbatim abstract or TLDR provided. You MAY NOT use knowledge
     of the paper, the related work, or the field beyond what is
     explicitly given in the inputs.

  2. **Six fields, all required:**
       problem:     what problem does the related paper address?
       method:      what method does it use?
       dataset:     what dataset does it evaluate on? (null if none stated)
       metric:      what metric does it report? (null if none stated)
       difference:  how does it DIFFER from the claim's paper?
       agreement:   where does it AGREE with the claim's paper?

  3. **Cite the abstract.** Each field's text should be a 1-3 sentence
     summary that an evaluator can trace back to the verbatim input.
     If the abstract does not address a field, set ``dataset`` or
     ``metric`` to null, and use "(abstract does not address)" for
     ``problem`` / ``method`` / ``difference`` / ``agreement``.

  4. **Be specific.** "Uses a transformer" is unhelpful; "Uses
     BART-base fine-tuned on CNN/DailyMail" is the goal.

Output schema is enforced via Structured Outputs
(response_format.json_schema strict=True). Any deviation fails the
call. If the abstract / TLDR is too sparse to compare, return the
sparse-field placeholders — do NOT guess.
"""


class LLMClient:
    """OpenAI wrapper that exposes a typed ``extract_claims`` method."""

    def __init__(self, settings: Settings) -> None:
        self._settings = settings
        # ``proxy=None`` disables proxying via env vars
        # (``all_proxy``/``HTTPS_PROXY``). Necessary because httpx 0.28
        # does not understand ``socks://`` — see module docstring.
        self._client = OpenAI(
            api_key=settings.openai_api_key,
            base_url=settings.openai_base_url,
            # ``OpenAI`` ships its own vendored ``httpx2`` and (in newer
            # SDK versions) annotates ``http_client`` as ``httpx2.Client``.
            # Our ``httpx.Client(proxy=None)`` is API-compatible at
            # runtime; tell mypy to stop checking.
            http_client=httpx.Client(proxy=None),  # type: ignore[arg-type]
            timeout=_DEFAULT_REQUEST_TIMEOUT_SECONDS,
        )
        # Phase 8: SafetyGate wraps every LLM call at the SDK seam
        # (see docs/architecture/phase-8-design.md §2). The gate
        # redacts credential spans and detects prompt-injection
        # attempts; it never raises on detection — the violations
        # list is fired through ``_on_violations`` (set by the
        # workflow layer to persist to ``state.errors``).
        self._gate = SafetyGate()
        self._on_violations: (
            "Callable[[str, list[SafetyViolation]], None] | None"
        ) = None

    # ------------------------------------------------------------------
    # Claim extraction
    # ------------------------------------------------------------------

    def extract_claims(self, paper: Paper) -> list[Claim]:
        """Call OpenAI with the ``ClaimList`` JSON schema and parse the response.

        :raises ClaimExtractionError: if the API call fails, the
            response fails schema validation, or the parsed list is
            empty.
        """
        user_payload = _build_user_payload(paper)
        schema = ClaimList.model_json_schema()

        # Phase 8: redact secrets in untrusted paper text BEFORE
        # the SDK call. Injections are detected but not mutated.
        messages = [
            {"role": "system", "content": _EXTRACT_SYSTEM_PROMPT},
            {"role": "user", "content": user_payload},
        ]
        gate_result = self._gate.wrap_messages(messages, kind="extract_claims")

        try:
            response = self._client.chat.completions.create(
                model=self._settings.openai_model_chat,
                messages=gate_result.messages,
                response_format={
                    "type": "json_schema",
                    "json_schema": {
                        "name": "claim_list",
                        "strict": True,
                        "schema": schema,
                    },
                },
            )
        except (APIConnectionError, APITimeoutError) as exc:
            raise ClaimExtractionError(
                f"LLM connection/timeout: {exc.__class__.__name__}: {exc}"
            ) from exc
        except AuthenticationError as exc:
            raise ClaimExtractionError(
                f"LLM auth error (check OPENAI_API_KEY): {exc}"
            ) from exc
        except APIStatusError as exc:
            raise ClaimExtractionError(
                f"LLM returned {exc.status_code}: {exc.message}"
            ) from exc

        if not response.choices:
            raise ClaimExtractionError("LLM returned no choices")

        raw = response.choices[0].message.content
        if not raw:
            raise ClaimExtractionError("LLM returned empty content")

        try:
            parsed = json.loads(raw)
        except json.JSONDecodeError as exc:
            raise ClaimExtractionError(f"LLM returned non-JSON content: {exc}") from exc

        try:
            claim_list = ClaimList.model_validate(parsed)
        except ValidationError as exc:
            raise ClaimExtractionError(f"LLM output failed schema validation: {exc}") from exc

        if not claim_list.claims:
            raise ClaimExtractionError("LLM returned an empty claim list")

        if gate_result.violations and self._on_violations is not None:
            self._on_violations("extract_claims", gate_result.violations)

        return claim_list.claims

    # ------------------------------------------------------------------
    # Verification (Phase 6)
    # ------------------------------------------------------------------

    def verdict_for_claim(
        self,
        *,
        claim: Claim,
        paper_evidence: PaperEvidence,
        candidates: list[RetrieveMatch],
        deterministic_discrepancies: list[Discrepancy],
    ) -> Verification:
        """Call OpenAI with the ``Verification`` JSON schema and parse.

        Mirrors :meth:`extract_claims` — same SDK call shape, same
        error mapping, but:

          - the system prompt is :data:`_VERIFY_SYSTEM_PROMPT`
            (the no-model-knowledge rule, per
            ``docs/specs/spec-summary.md:148-150``);
          - the response schema is :class:`Verification`
            (``model_json_schema()``);
          - errors map to :class:`VerificationLLMError` (NOT
            :class:`ClaimExtractionError` — the two are
            deliberately separate so the router can map verifier
            failures to a distinct ``error_code``);
          - the user payload includes the deterministic
            discrepancies so the LLM doesn't re-emit them.

        :raises VerificationLLMError: if the API call fails, the
            response fails schema validation, or the parsed
            verification has no ``claim_id``.
        """
        user_payload = _build_verify_payload(
            claim=claim,
            paper_evidence=paper_evidence,
            candidates=candidates,
            deterministic_discrepancies=deterministic_discrepancies,
        )
        schema = Verification.model_json_schema()

        # Phase 8: redact secrets + detect injections in the
        # claim text, paper evidence quote, candidate signatures,
        # and candidate docstrings. The system prompt is ours and
        # never matches.
        messages = [
            {"role": "system", "content": _VERIFY_SYSTEM_PROMPT},
            {"role": "user", "content": user_payload},
        ]
        gate_result = self._gate.wrap_messages(messages, kind="verdict")

        try:
            response = self._client.chat.completions.create(
                model=self._settings.openai_model_chat,
                messages=gate_result.messages,
                response_format={
                    "type": "json_schema",
                    "json_schema": {
                        "name": "verification",
                        "strict": True,
                        "schema": schema,
                    },
                },
            )
        except (APIConnectionError, APITimeoutError) as exc:
            raise VerificationLLMError(
                f"LLM connection/timeout: {exc.__class__.__name__}: {exc}"
            ) from exc
        except AuthenticationError as exc:
            raise VerificationLLMError(
                f"LLM auth error (check OPENAI_API_KEY): {exc}"
            ) from exc
        except APIStatusError as exc:
            raise VerificationLLMError(
                f"LLM returned {exc.status_code}: {exc.message}"
            ) from exc

        if not response.choices:
            raise VerificationLLMError("LLM returned no choices")

        raw = response.choices[0].message.content
        if not raw:
            raise VerificationLLMError("LLM returned empty content")

        try:
            parsed = json.loads(raw)
        except json.JSONDecodeError as exc:
            raise VerificationLLMError(
                f"LLM returned non-JSON content: {exc}"
            ) from exc

        try:
            verification = Verification.model_validate(parsed)
        except ValidationError as exc:
            raise VerificationLLMError(
                f"LLM output failed schema validation: {exc}"
            ) from exc

        if not verification.claim_id:
            raise VerificationLLMError("LLM returned empty claim_id")

        # Defensive: ensure the LLM's claim_id matches the input.
        # If they differ, the LLM has lost context and we should
        # not trust the verification. Surface as VerificationLLMError
        # so the workflow can decide whether to retry or coerce.
        if verification.claim_id != claim.claim_id:
            raise VerificationLLMError(
                f"LLM returned claim_id={verification.claim_id!r}, "
                f"expected {claim.claim_id!r}"
            )

        # Defensive: status sanity check. The LLM should never emit
        # a status that's not in the enum; if it does, surface as a
        # verification failure rather than silently downgrading.
        if verification.status not in (
            VerificationStatus.VERIFIED,
            VerificationStatus.PARTIALLY_VERIFIED,
            VerificationStatus.CONTRADICTED,
            VerificationStatus.UNVERIFIED,
        ):
            raise VerificationLLMError(
                f"LLM returned invalid status: {verification.status!r}"
            )

        if gate_result.violations and self._on_violations is not None:
            self._on_violations("verdict", gate_result.violations)

        return verification

    # ------------------------------------------------------------------
    # Related-work comparison (Phase 7)
    # ------------------------------------------------------------------

    def extract_comparison(self, *, claim: Claim, paper: ScholarPaper) -> Comparison:
        """Call OpenAI with the :class:`Comparison` JSON schema.

        Mirrors :meth:`verdict_for_claim` exactly — same SDK call
        shape, same error-mapping convention — but the input is the
        claim + one candidate paper and the output is a 6-field
        :class:`Comparison`:

          - **system prompt**: :data:`_COMPARE_SYSTEM_PROMPT` (the
            no-model-knowledge rule, same as the verifier);
          - **user payload**: claim + paper metadata (title,
            authors, year, venue, optional TLDR + abstract);
          - **response schema**: :class:`Comparison`;
          - **errors map to**: :class:`LiteratureComparisonError`
            (NOT :class:`VerificationLLMError` — the two layers are
            deliberately separate so the workflow can isolate per-
            paper failures without aborting the rest of the run).

        Per-paper isolation: callers should wrap this call in
        ``try/except LiteratureComparisonError``; one paper's LLM
        failure must NOT abort the rest of the related-work run.

        :raises LiteratureComparisonError: on any LLM / parse /
            validation failure.
        """
        user_payload = _build_compare_payload(claim=claim, paper=paper)
        schema = Comparison.model_json_schema()

        # Phase 8: redact secrets + detect injections in the
        # claim text, the related paper's title / abstract /
        # TLDR / venue / authors.
        messages = [
            {"role": "system", "content": _COMPARE_SYSTEM_PROMPT},
            {"role": "user", "content": user_payload},
        ]
        gate_result = self._gate.wrap_messages(messages, kind="compare")

        try:
            response = self._client.chat.completions.create(
                model=self._settings.openai_model_chat,
                messages=gate_result.messages,
                response_format={
                    "type": "json_schema",
                    "json_schema": {
                        "name": "comparison",
                        "strict": True,
                        "schema": schema,
                    },
                },
            )
        except (APIConnectionError, APITimeoutError) as exc:
            raise LiteratureComparisonError(
                f"LLM connection/timeout: {exc.__class__.__name__}: {exc}"
            ) from exc
        except AuthenticationError as exc:
            raise LiteratureComparisonError(
                f"LLM auth error (check OPENAI_API_KEY): {exc}"
            ) from exc
        except APIStatusError as exc:
            raise LiteratureComparisonError(
                f"LLM returned {exc.status_code}: {exc.message}"
            ) from exc

        if not response.choices:
            raise LiteratureComparisonError("LLM returned no choices")

        raw = response.choices[0].message.content
        if not raw:
            raise LiteratureComparisonError("LLM returned empty content")

        try:
            parsed = json.loads(raw)
        except json.JSONDecodeError as exc:
            raise LiteratureComparisonError(
                f"LLM returned non-JSON content: {exc}"
            ) from exc

        try:
            comparison = Comparison.model_validate(parsed)
        except ValidationError as exc:
            raise LiteratureComparisonError(
                f"LLM output failed schema validation: {exc}"
            ) from exc

        if gate_result.violations and self._on_violations is not None:
            self._on_violations("compare", gate_result.violations)

        return comparison

    # ------------------------------------------------------------------
    # Readiness probe
    # ------------------------------------------------------------------

    def check_ready(self) -> tuple[bool, str | None]:
        """Probe the LLM endpoint with a one-token call.

        Returns ``(True, None)`` on success, ``(False, "<error>")`` on
        failure. Mirrors :func:`claim2code_api.db.session.check_db_ready`
        so future phases can wire LLM readiness into ``/health/ready``.
        """
        try:
            self._client.chat.completions.create(
                model=self._settings.openai_model_chat,
                messages=[{"role": "user", "content": "ping"}],
                max_tokens=1,
                timeout=10.0,
            )
        except Exception as exc:  # noqa: BLE001 — probe is best-effort
            return False, f"{exc.__class__.__name__}: {str(exc)[:200]}"
        return True, None


# ----------------------------------------------------------------------
# Module-level lazy singleton (mirrors db/session.py)
# ----------------------------------------------------------------------

_client: LLMClient | None = None
_client_lock = Lock()


def get_llm_client() -> LLMClient:
    """Return the lazily-initialised process-wide LLMClient."""
    global _client
    if _client is None:
        with _client_lock:
            if _client is None:
                _client = LLMClient(get_settings())
    return _client


def reset_llm_for_tests() -> None:
    """Drop the cached client so the next ``get_llm_client`` rebuilds it.

    Tests use this to pick up env-var changes (e.g. a different
    ``OPENAI_BASE_URL`` pointing at a mock server).
    """
    global _client
    with _client_lock:
        _client = None


